// Mapeamento gracioso para acentuação comum em Português
static char sanitize_char(unsigned char c) {
    if (c < 128) return (char)c;

    // ISO-8859-1 / Windows-1252 acentos comuns
    switch (c) {
        case 0xC1: case 0xC0: case 0xC3: case 0xE1: case 0xE0: case 0xE3: return 'a';
        case 0xC9: case 0xCA: case 0xE9: case 0xEA:                         return 'e';
        case 0xCD: case 0xED:                                               return 'i';
        case 0xD3: case 0xD4: case 0xD5: case 0xF3: case 0xF4: case 0xF5: return 'o';
        case 0xDA: case 0xFA:                                               return 'u';
        case 0xC7: case 0xE7:                                               return 'c';
        default: return ' ';
    }
}

void font_draw_char(int x, int y, char c, u32 color, bool shadow) {
    unsigned char uc = (unsigned char)c;
    char clean_c = sanitize_char(uc);
    int idx = (unsigned char)clean_c;
    if (idx < 0 || idx >= 128) idx = ' ';

    const u8* rows = s_font_8x8[idx];

    // Sombra projetada em 1px inferior e direito (Preto translúcido retrô)
    if (shadow) {
        u32 shadow_color = 0x050C07FF;
        for (int row = 0; row < 8; row++) {
            u8 bits = rows[row];
            if (!bits) continue;
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    hal_video_put_pixel(x + col + 1, y + row + 1, shadow_color);
                }
            }
        }
    }

    // Caractere principal
    for (int row = 0; row < 8; row++) {
        u8 bits = rows[row];
        if (!bits) continue;
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                hal_video_put_pixel(x + col, y + row, color);
            }
        }
    }
}

int font_draw_text(int x, int y, const char* text, u32 color, bool shadow) {
    if (!text) return x;
    return font_draw_text_len(x, y, text, (int)strlen(text), color, shadow);
}

int font_draw_text_len(int x, int y, const char* text, int max_chars, u32 color, bool shadow) {
    if (!text || max_chars <= 0) return x;

    int cur_x = x;
    int len = (int)strlen(text);
    int printed = 0;

    for (int i = 0; i < len && printed < max_chars; i++) {
        unsigned char c = (unsigned char)text[i];

        // Lida com caracteres UTF-8 de 2 bytes (ex: 'é' = 0xC3 0xA9)
        if (c == 0xC3 && i + 1 < len) {
            unsigned char next = (unsigned char)text[i + 1];
            char mapped = ' ';
            switch (next) {
                case 0xA1: case 0xA0: case 0xA2: case 0xA3: mapped = 'a'; break; // á, à, â, ã
                case 0xA9: case 0xAA:                         mapped = 'e'; break; // é, ê
                case 0xAD:                                     mapped = 'i'; break; // í
                case 0xB3: case 0xB4: case 0xB5:             mapped = 'o'; break; // ó, ô, õ
                case 0xBA:                                     mapped = 'u'; break; // ú
                case 0xA7:                                     mapped = 'c'; break; // ç
                case 0x81: case 0x82: case 0x83:             mapped = 'A'; break; // Á, Â, Ã
                case 0x89:                                     mapped = 'E'; break; // É
                case 0x93: case 0x95:                         mapped = 'O'; break; // Ó, Õ
                case 0x87:                                     mapped = 'C'; break; // Ç
                default: mapped = ' '; break;
            }
            font_draw_char(cur_x, y, mapped, color, shadow);
            cur_x += 7; // Espaçamento proporcional retrô
            printed++;
            i++; // consome o segundo byte
            continue;
        }

        font_draw_char(cur_x, y, (char)c, color, shadow);
        cur_x += (c == ' ') ? 4 : 7; // Espaço mais estreito (4px), letras 7px
        printed++;
    }

    return cur_x;
}

int font_get_text_width(const char* text) {
    if (!text) return 0;
    int width = 0;
    int len = (int)strlen(text);
    for (int i = 0; i < len; i++) {
        unsigned char c = (unsigned char)text[i];
        if (c == 0xC3 && i + 1 < len) {
            width += 7;
            i++;
            continue;
        }
        width += (c == ' ') ? 4 : 7;
    }
    return width;
}

int font_draw_text_multiline(int x, int y, int max_w, int line_h, const char* text, u32 color, bool shadow) {
    if (!text || max_w <= 0) return 0;

    int cur_x = x;
    int cur_y = y;
    int lines_count = 1;
    const char* p = text;

    while (*p) {
        if (*p == '\n') {
            cur_x = x;
            cur_y += line_h;
            lines_count++;
            p++;
            continue;
        }

        // Pula espaços no início de nova linha
        if (cur_x == x && *p == ' ') {
            p++;
            continue;
        }

        // Mede a extensão em pixels e bytes da próxima palavra
        const char* word_start = p;
        int word_w = 0;
        int word_bytes = 0;

        while (*p && *p != ' ' && *p != '\n') {
            unsigned char c = (unsigned char)*p;
            if (c == 0xC3 && *(p + 1)) {
                word_w += 7;
                word_bytes += 2;
                p += 2;
            } else {
                word_w += (c == ' ') ? 4 : 7;
                word_bytes += 1;
                p += 1;
            }
        }

        // Quebra automática se a palavra ultrapassar max_w
        if (cur_x + word_w > x + max_w && cur_x > x) {
            cur_x = x;
            cur_y += line_h;
            lines_count++;
        }

        // Renderiza a palavra
        font_draw_text_len(cur_x, cur_y, word_start, word_bytes, color, shadow);
        cur_x += word_w;

        // Se o próximo caractere for espaço e couber na linha, avança
        if (*p == ' ') {
            if (cur_x + 4 <= x + max_w) {
                cur_x += 4;
            }
            p++;
        }
    }

    return lines_count;
}

